"""Write results/selene.md from results/selene_noiseless.csv and
results/selene_depolarizing.csv (every number in the summary is recomputed
here from the CSVs).

    python3 selene/make_summary.py
"""
import math
import os
import sys

import numpy as np
import pandas as pd

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RESULTS = os.path.join(ROOT, "results")
OUT = os.path.join(RESULTS, "selene.md")


def fmt(x, nd=4):
    if isinstance(x, float) and math.isnan(x):
        return "nan"
    return f"{x:.{nd}f}" if isinstance(x, float) else str(x)


def md_table(df, cols, nd=4):
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for _, r in df.iterrows():
        lines.append("| " + " | ".join(fmt(r[c], nd) if isinstance(r[c], (float, np.floating)) else str(r[c]) for c in cols) + " |")
    return "\n".join(lines)


def main():
    nl = pd.read_csv(os.path.join(RESULTS, "selene_noiseless.csv"))
    dp = pd.read_csv(os.path.join(RESULTS, "selene_depolarizing.csv"))
    calib = os.path.join(RESULTS, "selene_calibration.txt")
    calib_txt = open(calib).read().strip() if os.path.exists(calib) else "(selene_calibration.txt missing)"
    log = os.path.join(RESULTS, "selene_run.log")
    log_txt = open(log).read().strip() if os.path.exists(log) else ""

    shots = int(nl["shots"].iloc[0])
    n_runs = len(nl)
    per_pipe = nl.groupby("pipeline").size().to_dict()
    per_fam = nl.groupby("family").size().to_dict()
    flagged = nl[nl["flag"] == 1]
    worst = nl.sort_values("TVD_over_scale", ascending=False).head(10)
    worst_exact = nl.sort_values("TVD_over_expected", ascending=False).head(10)
    chi = nl[nl["support_size"] <= 64]
    chi_multi = chi[chi["support_size"] > 1]
    chi_low = chi_multi[chi_multi["chi2_p"] < 0.01]
    chi_reliable = chi_multi[chi_multi["chi2_cells_below_5"] == 0]
    chi_low_reliable = chi_reliable[chi_reliable["chi2_p"] < 0.01]
    pooled_low = chi_multi[chi_multi["chi2_p_pooled"] < 0.01]
    from scipy.stats import kstest
    ks = kstest(chi_reliable["chi2_p"].values, "uniform") if len(chi_reliable) > 0 else None
    ks_pooled = kstest(chi_multi["chi2_p_pooled"].values, "uniform")
    t_wall_total = nl["t_total"].sum()

    lines = []
    lines.append("# Selene (local emulator) runs of the compiled circuits\n")
    lines.append("Generated by `selene/make_summary.py` from `results/selene_noiseless.csv` and `results/selene_depolarizing.csv` "
                 "(produced by `selene/run_selene.py`; tests in `selene/test_selene.py`; error-model probe in `selene/calibrate_error_model.py`). "
                 "Nothing was submitted to Nexus or any cloud service; every run is `selene-sim` 0.3.4 on the local 2-core container.\n")
    lines.append("Tags: [F] verifiable from the CSVs or by rerunning the scripts; [O] judgement or assumption.\n")

    lines.append("## 1. Route that works\n")
    lines.append("[F] `results/compiled/<pipeline>/<file>.qasm` (hqslib1 header; gates `rz`, `U1q`, `RZZ`, `measure q[j] -> c[i]`) "
                 "-> `pytket.qasm.circuit_from_qasm` (OpTypes Rz, PhasedX, ZZPhase, Measure) -> `guppylang.guppy.load_pytket(name, circ)` "
                 "(signature `array[qubit, n] -> array[bool, n]`) -> a guppy `main` that allocates `n` qubits, calls the loaded function, "
                 "`discard_array`s the qubits and emits `result(\"c\", bits)` -> `selene_sim.build(main.compile())` -> "
                 "`runner.run_shots(Quest(random_seed=s), n_qubits=n, n_shots=2000, error_model=..., random_seed=s)`.")
    lines.append("[F] `load_pytket` accepted PhasedX, Rz, ZZPhase and Measure directly on every one of the %d compiled circuits; no rebase, "
                 "no HUGR export and no gate substitution was needed. The ZZPhase/U1q rejection anticipated in the brief did not occur." % n_runs)
    lines.append("[F] Bit order: the `result(\"c\", ...)` array is in classical-bit order c[0..n-1]; the bitstring `\"\".join(c)` therefore has c[0] as "
                 "its most significant bit, the convention of `bench/family_A/*.npy` and `compile.probs_from_measured_qasm`. "
                 "`selene/test_selene.py::test_measure_map_permutation` checks this with X on q[0] (and on q[2]) and the map q[0]->c[2], q[1]->c[0], q[2]->c[1] "
                 "(expected strings 001 and 010; both the Selene sample and `probs_from_measured_qasm` put all mass there).")
    lines.append("[F] Operational gotchas: (i) every proxy variable (`HTTPS_PROXY`, `https_proxy`, `HTTP_PROXY`, `http_proxy`, `NO_PROXY`, `no_proxy`) must be unset "
                 "or Selene's local TCP result stream hangs (the script pops them itself); (ii) `guppy.load_pytket` needs a unique function name per circuit in a process; "
                 "(iii) the first `build` in a process costs about 5-10 s (toolchain warm-up), later builds 0.2-0.6 s; "
                 "(iv) `run_shots` has its own `n_processes` argument, but circuits were parallelised instead with a 2-process `multiprocessing` spawn pool "
                 "(one `run_shots` call per circuit, `n_processes=1`), which Selene allowed without conflicts.")
    lines.append("[F] Seeding: `random_seed = sha256(pipeline/file/tag)[:4]`, stored in the CSV column `seed`; `test_seed_reproducible` checks that the same seed "
                 "reproduces the counts exactly and a different seed does not.\n")

    lines.append("## 2. Noiseless runs\n")
    lines.append(f"[F] {n_runs} runs = {per_fam.get('A', 0)} family-A (n <= 10: ladder/tfim/xxz, n in {{4,6,8,10}}, r in {{1,2,4}}, 4 instances) "
                 f"+ {per_fam.get('B1', 0)} family-B1 (n <= 10) circuits, over pipelines " +
                 ", ".join(f"{k} ({v})" for k, v in sorted(per_pipe.items())) +
                 f"; {shots} shots each; `IdealErrorModel`, `Quest` statevector backend.")
    lines.append("[F] Exact distribution: `compile.probs_from_measured_qasm` on the compiled QASM text (includes the measure map). "
                 f"Cross-check against the family reference (`bench/family_A/<stem>.npy`, or P0ref for B1): max over runs of max|p_exact - p_ref| = {nl['exact_vs_ref_maxdiff'].max():.2e}.")
    lines.append("[F] Metrics per run (columns of `selene_noiseless.csv`): Hellinger fidelity `F_H = (sum_i sqrt(p_i q_i))^2`, `TVD = 0.5 sum_i |p_i - q_i|`, "
                 "`support_size` = #{i : p_i > 1e-12}, `TVD_scale = sqrt(support/(2 pi shots))` (the scale stated in the brief), "
                 "`TVD_expected_exact = 0.5 sqrt(2/(pi shots)) sum_i sqrt(p_i (1-p_i))` (asymptotic mean sampling TVD for the actual p), "
                 "`flag = TVD > 4 TVD_scale`, `shots_outside_support`, `chi2_p` and `chi2_p_pooled` (support <= 64 only), `chi2_cells_below_5`, wall times, `counts`.")
    lines.append(f"[F] Expected sampling scale: with {shots} shots, `TVD_scale` runs from {nl['TVD_scale'].min():.4f} (support 1) to {nl['TVD_scale'].max():.4f} "
                 f"(support {int(nl['support_size'].max())}). The exact-p expectation `TVD_expected_exact` runs from {nl['TVD_expected_exact'].min():.4f} to {nl['TVD_expected_exact'].max():.4f}.")
    lines.append(f"[F] Max TVD over all runs: {nl['TVD'].max():.4f} ({nl.loc[nl['TVD'].idxmax(), 'pipeline']}/{nl.loc[nl['TVD'].idxmax(), 'file']}, support {int(nl.loc[nl['TVD'].idxmax(), 'support_size'])}). "
                 f"Max TVD/TVD_scale: {nl['TVD_over_scale'].max():.3f}. Max TVD/TVD_expected_exact: {nl['TVD_over_expected'].max():.3f} "
                 f"(median {nl['TVD_over_expected'].median():.3f}; for a correct circuit this ratio should scatter around 1).")
    lines.append(f"[F] Flagged runs (TVD > 4 x TVD_scale): {len(flagged)}.")
    if len(flagged):
        lines.append(md_table(flagged, ["pipeline", "file", "support_size", "TVD", "TVD_scale", "TVD_over_scale"]))
    lines.append(f"[F] Shots landing outside the exact support: {int(nl['shots_outside_support'].sum())} in total across all runs "
                 f"({int((nl['shots_outside_support'] > 0).sum())} runs with any). [O] A wrong measure map or a wrong gate would put shots on zero-probability strings for the "
                 f"{int((nl['support_size'] < 2 ** nl['n']).sum())} runs whose support is smaller than 2^n; none did.")
    lines.append(f"[F] F_H: min {nl['F_H'].min():.4f}, median {nl['F_H'].median():.4f}. [O] F_H of a finite sample is biased below 1 by about (support-1)/(4 shots) "
                 f"(0.13 for support 1024), so F_H is not a pass/fail statistic here; TVD against its expected scale is.")
    lines.append(f"[F] Chi-square against the exact multinomial, restricted to support <= 64: {len(chi)} runs, of which {len(chi) - len(chi_multi)} have support 1 "
                 f"(p-value defined as 1 when all shots land on the single outcome, which they did) and {len(chi_multi)} have 2..64 outcomes. "
                 f"Raw chi-square (`chi2_p`): {len(chi_low)} of the {len(chi_multi)} have p < 0.01, but {int((chi_multi['chi2_cells_below_5'] > 0).sum())} of the {len(chi_multi)} runs have cells with expected count < 5, "
                 f"where the chi-square approximation fails; on the {len(chi_reliable)} runs with every expected cell >= 5, {len(chi_low_reliable)} have p < 0.01"
                 + (f" and the KS test of their p-values against Uniform(0,1) gives statistic {ks.statistic:.3f}, p = {ks.pvalue:.3f}." if ks is not None else "."))
    lines.append(f"[F] Pooled chi-square (`chi2_p_pooled`: support cells with expected count < 5 merged into one cell, merged further until every cell is >= 5): "
                 f"{len(pooled_low)} of {len(chi_multi)} runs have p < 0.01 (expected {0.01 * len(chi_multi):.1f} under the null); "
                 f"{int((chi_multi['chi2_p_pooled'] < 0.05).sum())} have p < 0.05 (expected {0.05 * len(chi_multi):.1f}); "
                 f"KS test of all {len(chi_multi)} pooled p-values against Uniform(0,1): statistic {ks_pooled.statistic:.3f}, p = {ks_pooled.pvalue:.3f}.")
    if len(pooled_low):
        lines.append("[F] Runs with pooled chi2 p < 0.01:")
        lines.append(md_table(pooled_low.sort_values("chi2_p_pooled"), ["pipeline", "file", "support_size", "chi2_p_pooled", "chi2_p", "chi2_cells_below_5", "TVD", "TVD_expected_exact"]))
    recheck = os.path.join(RESULTS, "selene_recheck.txt")
    if os.path.exists(recheck):
        lines.append("[F] Those runs were re-sampled with fresh seeds and 20000 shots (`selene/recheck_lowp.py`, output `results/selene_recheck.txt`); none of the deviations persists:")
        lines.append("```\n" + open(recheck).read().strip() + "\n```")
    lines.append("[F] Sparse counts of every run are stored in the CSV column `counts` (`index:count;...`, index = int(bitstring, 2), c[0] most significant) so every metric can be recomputed without rerunning Selene.")
    lines.append("\n[F] Ten largest TVD / TVD_scale:")
    lines.append(md_table(worst, ["pipeline", "file", "n", "support_size", "TVD", "TVD_scale", "TVD_over_scale", "TVD_expected_exact", "TVD_over_expected"]))
    lines.append("\n[F] Ten largest TVD / TVD_expected_exact:")
    lines.append(md_table(worst_exact, ["pipeline", "file", "n", "support_size", "TVD", "TVD_expected_exact", "TVD_over_expected", "chi2_p_pooled"]))
    lines.append("\n[F] Per-pipeline summary:")
    g = nl.groupby("pipeline").agg(runs=("file", "size"), max_TVD=("TVD", "max"), max_TVD_over_scale=("TVD_over_scale", "max"),
                                   median_TVD_over_expected=("TVD_over_expected", "median"), flagged=("flag", "sum"),
                                   outside=("shots_outside_support", "sum"), t_total_s=("t_total", "sum")).reset_index()
    lines.append(md_table(g, list(g.columns), nd=3))
    lines.append(f"\n[F] Timing (noiseless): sum of per-run wall times {t_wall_total:.0f} s (load {nl['t_load'].sum():.0f} s, guppy+build {nl['t_build'].sum():.0f} s, "
                 f"run {nl['t_run'].sum():.0f} s); per run median {nl['t_total'].median():.2f} s, max {nl['t_total'].max():.2f} s "
                 f"({nl.loc[nl['t_total'].idxmax(), 'pipeline']}/{nl.loc[nl['t_total'].idxmax(), 'file']}). Elapsed wall time with 2 processes: see the log excerpt in section 5.\n")

    lines.append("[F] Reproducibility: the whole driver was run twice (the first time while another job shared the 2 cores: noiseless 675 s, total 746 s; the second time noiseless 465 s, total 534 s). "
                 "Every `TVD`, `F_H` and `F_H_selene_depol` value was bit-identical between the two runs (checked by merging the two CSVs on pipeline/file/variant), and metrics recomputed from the "
                 "stored `counts` column reproduce the CSV values to 1e-12 on 40 random rows.\n")
    lines.append("## 3. Depolarising runs versus the density-matrix proxy\n")
    lines.append("[F] `selene_sim.DepolarizingErrorModel(random_seed=None, p_1q=0.0, p_2q=0.0, p_meas=0.0, p_init=0.0)` (signature read with `inspect.signature`). "
                 "The user guide gives no convention, so `selene/calibrate_error_model.py` measured it (20000 shots per probe, p = 0.3):\n")
    lines.append("```\n" + calib_txt + "\n```")
    lines.append("[F] Reading of the probe: Rz is noiseless (0 flips in 20000 shots after 20 Rz gates at p_1q = 0.3); a zero-angle PhasedX still receives noise; "
                 "after one X gate the flip rate is 0.2051 +/- 0.0029 against 2p/3 = 0.200 for 'uniformly random non-identity Pauli with probability p' and p/2 = 0.150 for "
                 "'uniformly random Pauli including identity'; after one ZZPhase the rate of leaving 00 is 0.2442 +/- 0.0030 against 12p/15 = 0.240 (non-identity) and "
                 "12p/16 = 0.225 (any Pauli); p_meas is a symmetric readout flip (0.3061 and 0.3038 on |0> and |1>); p_init flips the prepared state with probability p (0.2979). "
                 "[O] These are the conventions of `noise/dm_sim.py` (p1: (1-p) rho + p/3 sum P rho P; p2: (1-p) rho + p/15 sum P rho P; Rz virtual), so the two models agree gate by gate "
                 "except that the proxy's readout flip is asymmetric (9e-4 / 1.8e-3) while Selene's is one number.")
    lines.append("[F] Parameters: p_1q = 7.3e-5, p_2q = 1.29e-3 (H2-2E defaults, `docs/platform_notes.md` 3.3). Two variants: `gates_only` (p_meas = p_init = 0) and "
                 "`gates_meas_init` (p_meas = 1.35e-3 = mean of the H2-2E 0-outcome and 1-outcome flip rates [O: assumption, Selene has one symmetric rate], p_init = 4e-5). "
                 "The proxy column is `results/family_A_proxy_h22e.csv` / `results/family_B1_proxy_h22e.csv` (noise set `NOISE_H22E`: p1, p2, p_meas_0, p_meas_1, p_init), "
                 "so `gates_meas_init` is the like-for-like comparison and `gates_only` is expected to sit above the proxy.")
    lines.append("[F] Comparison statistic: the proxy's F_H is exact (density matrix) while Selene's is from %d shots, and a finite sample biases F_H downward. "
                 "So for each run the proxy's noisy distribution was regenerated with `noise/dm_sim.py` (the same code that produced the proxy CSV; its exact F_H is reproduced in "
                 "`F_H_proxy_exact`), %d multinomial samples of %d shots were drawn from it, and their F_H mean and sd (`F_H_proxy_sampled_mean`, `F_H_proxy_sampled_sd`) are the "
                 "prediction and the sampling error for Selene's `F_H_selene_depol`. `z = (F_H_selene_depol - F_H_proxy_sampled_mean) / F_H_proxy_sampled_sd`; `agree_2sd` = |z| <= 2. "
                 "`F_H_selene_noiseless_sameseed` is the noiseless sample with the same seed (shows the pure sampling bias). `TVD_selene_vs_proxy` and `TVD_expected_sampling` compare the two "
                 "distributions directly." % (shots, 400, shots))
    for variant, sub in dp.groupby("variant"):
        n_ok = int((sub["agree_2sd"] == 1).sum())
        lines.append(f"\n### Variant `{variant}` ({len(sub)} runs: {sub['file'].nunique()} circuits x pipelines P0, P2)\n")
        lines.append(f"[F] |z| <= 2 in {n_ok}/{len(sub)} runs; mean z = {sub['z'].mean():+.2f}, sd of z = {sub['z'].std(ddof=1):.2f} (1.00 expected if the two models agree and only sampling noise remains); "
                     f"max |z| = {sub['z'].abs().max():.2f}. Mean (F_H_selene_depol - F_H_proxy_exact) = {(sub['F_H_selene_depol'] - sub['F_H_proxy_exact']).mean():+.4f}; "
                     f"mean (F_H_selene_depol - F_H_proxy_sampled_mean) = {(sub['F_H_selene_depol'] - sub['F_H_proxy_sampled_mean']).mean():+.4f}. "
                     f"Max TVD_selene_vs_proxy / TVD_expected_sampling = {(sub['TVD_selene_vs_proxy'] / sub['TVD_expected_sampling']).max():.2f}.")
        cols = ["family", "file", "pipeline", "n", "n_2q", "n_1q", "support_size", "F_H_proxy_exact", "F_H_proxy_sampled_mean", "F_H_proxy_sampled_sd",
                "F_H_selene_depol", "z", "agree_2sd", "F_H_selene_noiseless_sameseed", "TVD_selene_vs_proxy", "TVD_expected_sampling"]
        lines.append(md_table(sub.sort_values(["family", "n", "file", "pipeline"]), cols))
    lines.append(f"\n[F] Depolarising timing: sum of per-run wall times {dp['t_total'].sum():.0f} s for {len(dp)} runs (each run also draws the noiseless same-seed sample and runs the density-matrix proxy).")
    lines.append("[O] What this does and does not show: with 2000 shots the comparison resolves 1 - F_H to about 0.004 on the support-1 B1 circuits and to 0.002-0.01 elsewhere; "
                 "agreement at that level between two depolarising models that were shown above to share the same per-gate convention is expected and confirms the proxy's "
                 "implementation and its measure-map handling, not the proxy's fidelity to H2-2E (neither model contains the emission/leakage branch, crosstalk, "
                 "duration-based dephasing or the RZZ angle scaling of the published H2-2E model).\n")

    lines.append("## 4. Assumptions\n")
    lines.append("- [O] `support_size` counts p_i > 1e-12, so for Trotter circuits whose exact distribution has many tiny entries `TVD_scale` (which assumes a uniform distribution "
                 "on the support) overstates the sampling scale; `TVD_expected_exact` is the appropriate expectation and is reported alongside. The 4x flag uses `TVD_scale` as the brief asked.")
    lines.append("- [O] The chi-square p-value uses scipy's `chisquare` on the support cells; cells with expected count < 5 make it approximate (`chi2_cells_below_5`). Support 1 has zero degrees of freedom and is reported as p = 1 when every shot is on the support.")
    lines.append("- [O] Selene's `p_meas` was set to the mean of the two asymmetric H2-2E rates for the `gates_meas_init` variant.")
    lines.append("- [O] The Quest backend is a statevector simulator; `n_qubits` was set to the circuit's qubit count; no runtime or event hook beyond the defaults.")
    lines.append("- [F] Versions: selene-sim 0.3.4, guppylang 1.1.2, pytket 2.18.4, hugr 0.18.8, numpy %s, scipy %s, python %s.\n" % (np.__version__, __import__('scipy').__version__, sys.version.split()[0]))

    lines.append("## 5. Run log excerpt\n")
    lines.append("```\n" + log_txt[-3000:] + "\n```")
    with open(OUT, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
