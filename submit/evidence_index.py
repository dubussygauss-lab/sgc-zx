"""Execution evidence index for the submission checklist.

Reads every stored job payload results/emulator/<platform dir>/<pipeline>/<circuit>.json and the
job ledger results/emulator_jobs.csv. Writes results/EVIDENCE.md: one row per circuit payload with
platform, job ID, shots, noise option, counts check, HQC estimate and Hellinger fidelity F_H, and a
list of ledger rows that did not complete. Nothing is submitted.

Usage: python3 submit/evidence_index.py [--out results/EVIDENCE.md]
"""
import argparse
import glob
import json
import os

import pandas as pd

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
EMU = os.path.join(ROOT, "results", "emulator")
LEDGER = os.path.join(ROOT, "results", "emulator_jobs.csv")


def counts_ok(d: dict) -> bool:
    c = d.get("counts")
    return (not d.get("error")) and isinstance(c, dict) and len(c) > 0 \
        and int(sum(c.values())) == int(d.get("shots", -1))


def payload_rows() -> pd.DataFrame:
    rows = []
    for p in sorted(glob.glob(os.path.join(EMU, "*", "*", "*.json"))):
        with open(p) as f:
            d = json.load(f)
        rel = os.path.relpath(p, ROOT)
        run_dir = rel.split(os.sep)[2]
        opts = d.get("options") or {}
        rows.append({
            "platform": d.get("platform"),
            "run_dir": run_dir,
            "circuit": os.path.splitext(d.get("file", os.path.basename(p)))[0],
            "pipeline": d.get("pipeline"),
            "job_id": d.get("job_id"),
            "shots": d.get("shots"),
            "noisy": opts.get("noisy_simulation") if isinstance(opts, dict) else None,
            "counts_ok": counts_ok(d),
            "hqc_estimate": d.get("hqc_estimate"),
            "F_H": d.get("F_H"),
            "path": rel,
        })
    return pd.DataFrame(rows)


def fmt(x, nd):
    if x is None or (isinstance(x, float) and pd.isna(x)):
        return "-"
    return f"{float(x):.{nd}f}"


def render(df: pd.DataFrame, ledger: pd.DataFrame) -> str:
    L = ["# Execution evidence", "",
         "Generated by `submit/evidence_index.py` from the stored job payloads in `results/emulator/` and the job "
         "ledger `results/emulator_jobs.csv`. Every job was submitted through `aqora` to the Quantinuum platforms "
         "named below between 8 and 10 October 2026 (timestamps in the ledger). Nothing has run on hardware.", ""]
    ok = df[df.counts_ok]
    L.append("## Totals")
    L.append("")
    L.append("| Platform | Payloads with valid counts | Distinct job IDs | Shots | HQC estimate |")
    L.append("|---|---|---|---|---|")
    for plat, g in ok.groupby("platform"):
        h = g.hqc_estimate.dropna()
        L.append(f"| {plat} | {len(g)} | {g.job_id.nunique()} | {int(g.shots.sum())} | "
                 f"{fmt(h.sum(), 1) if len(h) else '-'} |")
    L.append("")
    L.append("HQC estimate = 5 + C (N_1q + 10 N_2q + 5 N_SPAM) / 5000 from the compiled circuit, as stored in each payload. "
             "On H2-Emulator several circuits share one batch job ID. H2-2SC is the syntax checker: its payloads carry no counts "
             "and are listed below with counts check no.")
    L.append("")
    L.append("## One row per circuit payload")
    L.append("")
    L.append("| Platform | Run | Circuit | Pipeline | Job ID | Shots | Noisy | Counts sum to shots | HQC est. | F_H | Payload |")
    L.append("|---|---|---|---|---|---|---|---|---|---|---|")
    for r in df.sort_values(["platform", "run_dir", "circuit", "pipeline"]).itertuples():
        L.append(f"| {r.platform} | {r.run_dir} | {r.circuit} | {r.pipeline} | `{r.job_id}` | {r.shots} | "
                 f"{r.noisy if r.noisy is not None else '-'} | {'yes' if r.counts_ok else 'no'} | "
                 f"{fmt(r.hqc_estimate, 1)} | {fmt(r.F_H, 4)} | `{r.path}` |")
    L.append("")
    bad = ledger[ledger.status != "COMPLETED"]
    L.append("## Ledger rows that did not complete")
    L.append("")
    L.append(f"{len(bad)} of {len(ledger)} ledger rows. The H2-Emulator rows failed on the simulation quota of the "
             "free tier. The first H2-2SC row failed on an upload error and was resubmitted.")
    L.append("")
    L.append("| Timestamp (UTC) | Platform | Circuit | Pipeline | Job ID | Status (first 60 characters) |")
    L.append("|---|---|---|---|---|---|")
    for r in bad.itertuples():
        jid = r.job_id if isinstance(r.job_id, str) else "-"
        L.append(f"| {r.timestamp} | {r.platform} | {r.file} | {r.pipeline} | `{jid}` | "
                 f"{str(r.status)[:60].replace('|', '/')} |")
    L.append("")
    L.append("## Where the results are used")
    L.append("")
    L.append("- Report tables E2 and E3 (appendix Section 3.7.1): `python3 submit/h22e_stats.py` and "
             "`python3 submit/h22e_pooled.py` recompute them from these payloads.")
    L.append("- Family C on H2-2E: `python3 submit/h22e_famC.py` (vbe_adder_7, all-zero input, run nexus_H2-2E_famC) and "
             "`python3 submit/h22e_famC_nz.py` (vbe_adder_7 on a = 28, b = 111, P0 vs L3, run nexus_H2-2E_famC_nz, "
             "pre-registered in `results/h22e_nonzero_prereg.md`); `python3 submit/h22e_multi.py` (cdkm_adder_10 P0 vs L3 and "
             "modadd_2n_10 P0 vs P2L3, three non-zero inputs each, 400 shots, run nexus_H2-2E_famC_multi, pre-registered in "
             "`results/h22e_multi_prereg.md`).")
    L.append("- Family B1 on non-zero inputs on H2-2E: `python3 submit/h22e_b1.py` (vbe_adder_3 P0 vs L3 on four inputs and "
             "hwb6 P0 vs P2L3 on three inputs, 400 shots, run nexus_H2-2E_famB1_multi, pre-registered in "
             "`results/h22e_b1_prereg.md`).")
    L.append("- H2-Emulator comparison (appendix Section 3.7): `results/emulator_nexus_H2-Emulator.csv`.")
    L.append("- Notebook run on H2-2SC: `report/notebook_executed.html`.")
    L.append("- Logs: `results/emu_*.log`, `results/fetch_*.log`.")
    L.append("")
    return "\n".join(L)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=os.path.join(ROOT, "results", "EVIDENCE.md"))
    a = ap.parse_args()
    df = payload_rows()
    ledger = pd.read_csv(LEDGER)
    text = render(df, ledger)
    with open(a.out, "w", encoding="utf-8") as f:
        f.write(text)
    ok = df[df.counts_ok]
    print(f"{len(df)} payloads, {len(ok)} with valid counts, {ok.job_id.nunique()} distinct job IDs; "
          f"{(ledger.status != 'COMPLETED').sum()} ledger rows not completed; wrote {os.path.relpath(a.out, ROOT)}")
    for plat, g in ok.groupby("platform"):
        print(plat, len(g), g.job_id.nunique(), fmt(g.hqc_estimate.dropna().sum(), 1))


if __name__ == "__main__":
    main()
