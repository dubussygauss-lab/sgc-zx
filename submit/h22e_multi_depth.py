"""Two-qubit gate count, two-qubit depth and total depth of the compiled programs of the
multi-input H2-2E run (results/compiled/<pipeline>/<circuit>_i<k>.qasm, the files submitted).
Writes results/h22e_multi_depth.md. Usage: python3 submit/h22e_multi_depth.py"""
import os
from pytket.qasm import circuit_from_qasm

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RUNS = [("cdkm_adder_10", ["P0", "L3"]), ("modadd_2n_10", ["P0", "P2L3"])]


def rows():
    out = []
    for c, pipes in RUNS:
        for k in (1, 2, 3):
            for p in pipes:
                q = circuit_from_qasm(os.path.join(ROOT, "results", "compiled", p, f"{c}_i{k}.qasm"))
                out.append((c, k, p, q.n_2qb_gates(), q.depth_2q(), q.depth()))
    return out


def main():
    L = ["# Depth of the compiled multi-input H2-2E programs", "",
         "Generated by `submit/h22e_multi_depth.py` from the submitted QASM in `results/compiled/`.", "",
         "| Circuit | Input | Pipeline | Two-qubit gates | Two-qubit depth | Depth |", "|---|---|---|---|---|---|"]
    for r in rows():
        L.append("| %s | i%d | %s | %d | %d | %d |" % r)
    open(os.path.join(ROOT, "results", "h22e_multi_depth.md"), "w").write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
