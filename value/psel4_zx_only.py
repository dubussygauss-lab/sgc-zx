"""Part of the PSEL4 saving that comes from the ZX candidates alone.

Baseline per circuit: min(L2, L3), the cheaper of pytket-quantinuum at optimisation level 2 (P0) and level 3.
ZX-only saving = (sum min(L2, L3) - sum PSEL4) / sum min(L2, L3). Reads value/psel4_ledger.csv and the
miter verdicts used by value/psel4_proven.py. Writes value/psel4_zx_only.md.
Usage: python3 value/psel4_zx_only.py
"""
import os
import sys

import pandas as pd

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "value"))
import psel4_proven  # noqa: E402


def compute() -> list:
    d = pd.read_csv(os.path.join(ROOT, "value", "psel4_ledger.csv"))
    v = psel4_proven.verdicts()
    c = d[d.family == "C"].copy()
    c["proven"] = [v.get((f, p)) == "proven" for f, p in zip(c.file, c.pick_PSEL4)]
    groups = [("Family C, 17 circuits with proven PSEL4 output", c[c.proven]),
              ("Family C, all 20 circuits", c),
              ("B1, 15 circuits", d[d.family == "B1"]),
              ("A, 180 Trotter circuits", d[d.family == "A"]),
              ("Grover use case, 2 circuits", d[d.family == "usecase"])]
    rows = []
    for name, x in groups:
        L2, L3 = x.hqc_P0.sum(), x.hqc_L3.sum()
        best = x[["hqc_P0", "hqc_L3"]].min(axis=1).sum()
        p = x.hqc_PSEL4.sum()
        rows.append({"set": name, "n": len(x), "L2": L2, "L3": L3, "min_L2_L3": best, "PSEL4": p,
                     "vs_L2": 100 * (L2 - p) / L2, "vs_L3": 100 * (L3 - p) / L3,
                     "zx_only": 100 * (best - p) / best,
                     "zx_picks": int(x.pick_PSEL4.isin(["P2", "P2L3"]).sum())})
    return rows


def main():
    rows = compute()
    L = ["# PSEL4 saving split into level choice and ZX", "",
         "Generated by `python3 value/psel4_zx_only.py` from `value/psel4_ledger.csv`. HQC at 1000 shots. "
         "min(L2, L3) is the cheaper of pytket-quantinuum level 2 and level 3 per circuit. "
         "The ZX-only saving is PSEL4 against that per-circuit minimum.", "",
         "| Set | Circuits | L2 | L3 | min(L2, L3) | PSEL4 | Saved vs L2 % | Saved vs L3 % | ZX-only saved % | ZX picks |",
         "|---|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        L.append("| %s | %d | %.1f | %.1f | %.1f | %.1f | %.2f | %.2f | %.2f | %d |" % (
            r["set"], r["n"], r["L2"], r["L3"], r["min_L2_L3"], r["PSEL4"], r["vs_L2"], r["vs_L3"], r["zx_only"], r["zx_picks"]))
    L.append("")
    open(os.path.join(ROOT, "value", "psel4_zx_only.md"), "w").write("\n".join(L))
    print("\n".join(L))


if __name__ == "__main__":
    main()
