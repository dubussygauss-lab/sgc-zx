"""PSEL4 on family C restricted to circuits whose PSEL4 output is proven equal to its input.

Reads value/psel4_ledger.csv, results/family_C_equivalence_psel4.csv (L3 / P2L3 picks) and
results/family_C_equivalence.csv (P0 / P2 picks, comparison == pipeline). Writes value/psel4_proven.md.
Usage: python3 value/psel4_proven.py
"""
import os
import pandas as pd

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def verdicts() -> dict:
    v = {}
    old = pd.read_csv(os.path.join(ROOT, "results", "family_C_equivalence.csv"))
    for r in old.itertuples():
        if r.comparison == r.pipeline:
            v[(r.file, r.pipeline)] = r.verdict
    new = pd.read_csv(os.path.join(ROOT, "results", "family_C_equivalence_psel4.csv"))
    for r in new.itertuples():
        v[(r.file, r.pick)] = r.verdict
    return v


def compute() -> dict:
    d = pd.read_csv(os.path.join(ROOT, "value", "psel4_ledger.csv"))
    c = d[d.family == "C"].copy()
    v = verdicts()
    c["verdict"] = [v.get((f, p), "missing") for f, p in zip(c.file, c.pick_PSEL4)]
    pr = c[c.verdict == "proven"]
    un = c[c.verdict != "proven"]
    def tot(x):
        return x.hqc_P0.sum(), x.hqc_L3.sum(), x.hqc_PSEL4.sum()
    L2a, L3a, Pa = tot(c)
    L2p, L3p, Pp = tot(pr)
    return {"n": len(c), "n_proven": len(pr), "unproven": list(zip(un.file, un.pick_PSEL4, un.verdict)),
            "L2p": L2p, "L3p": L3p, "Pp": Pp,
            "save_L2_p": 100 * (L2p - Pp) / L2p, "save_L3_p": 100 * (L3p - Pp) / L3p,
            "share_unproven_L3": 100 * ((L3a - Pa) - (L3p - Pp)) / (L3a - Pa),
            "share_unproven_L2": 100 * ((L2a - Pa) - (L2p - Pp)) / (L2a - Pa),
            "saved_L3_all": L3a - Pa, "saved_L3_unproven": (L3a - Pa) - (L3p - Pp)}


def main():
    r = compute()
    L = ["# PSEL4 on family C, proven outputs only", "",
         "Generated by `python3 value/psel4_proven.py` from `value/psel4_ledger.csv` and the PyZX miter verdicts of "
         "`results/family_C_equivalence.csv` and `results/family_C_equivalence_psel4.csv`. HQC at 1000 shots.", "",
         "- [F] Family C circuits: %d. PSEL4 output proven equal to its input: %d." % (r["n"], r["n_proven"]),
         "- [F] Not proven: " + ", ".join("%s (%s, %s)" % (f.replace(".qasm", ""), p, v) for f, p, v in r["unproven"]) + ".",
         "- [F] On the %d proven circuits: L2 %.1f, L3 %.1f, PSEL4 %.1f HQC. PSEL4 saves %.2f %% against L2 and %.2f %% against L3."
         % (r["n_proven"], r["L2p"], r["L3p"], r["Pp"], r["save_L2_p"], r["save_L3_p"]),
         "- [F] Of the %.1f HQC that PSEL4 saves against L3 on all 20 circuits, %.1f HQC or %.1f %% comes from the unproven picks. "
         "Against L2 the unproven picks give %.1f %% of the saving." % (r["saved_L3_all"], r["saved_L3_unproven"], r["share_unproven_L3"], r["share_unproven_L2"]), ""]
    open(os.path.join(ROOT, "value", "psel4_proven.md"), "w").write("\n".join(L))
    print("\n".join(L))


if __name__ == "__main__":
    main()
